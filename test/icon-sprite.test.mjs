/* Every icon the code names is in the sprite (2026-10-28). js/ui/icons.js draws an icon as <use href="phosphor.svg#ph-NAME">,
   and a name the sprite lacks draws NOTHING, silently: the phone sheets asked for 'caret-up' from the day they were built and
   a collapsed sheet's handle showed no caret (Joey: "nothing about it that says expand me"). The sprite is generated by
   tools/make-icons.mjs from its ICONS list, so a new name goes there. Read here: every quoted name inside an icon(...) call -
   ternaries included (`icon(open ? 'caret-down' : 'caret-up')`) - in js/, its -fill variant when the call asks for fill. */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sprite = readFileSync(join(root, 'icons', 'phosphor.svg'), 'utf8');
const have = new Set([...sprite.matchAll(/<symbol id="ph-([a-z0-9-]+)"/g)].map((m) => m[1]));
const files = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? (f === 'vendor' ? [] : files(p)) : p.endsWith('.js') ? [p] : []; });

test('every icon named in an icon(...) call is a symbol in icons/phosphor.svg', () => {
  const missing = [];
  let calls = 0;
  for (const f of files(join(root, 'js'))) {
    const src = readFileSync(f, 'utf8');
    // the call's first argument: up to the options object or the closing parenthesis
    for (const m of src.matchAll(/\bicon\(([^,)]{1,160})(,\s*\{[^}]*\})?/g)) {
      const names = [...m[1].matchAll(/'([a-z0-9-]+)'/g)].map((x) => x[1]);
      if (!names.length) continue;
      calls++;
      const fill = m[2] && /fill:\s*true/.test(m[2]);
      for (const n of names) {
        if (!have.has(n)) missing.push(`${n} (${f.slice(root.length + 1)})`);
        if (fill && !have.has(n + '-fill')) missing.push(`${n}-fill (${f.slice(root.length + 1)})`);
      }
    }
  }
  assert.ok(calls > 20, `the scan found the calls (${calls})`);
  assert.deepEqual(missing, [], 'names missing from the sprite: add them to tools/make-icons.mjs ICONS and run it');
});

test('the collapsed and open sheet carets are both in the sprite', () => {
  assert.ok(have.has('caret-up') && have.has('caret-down'));
});
