/* Builds icons/phosphor.svg, an SVG sprite of the Phosphor icons the app uses, from
 * @phosphor-icons/core (a devDependency). Regular weight for idle, Fill for active, per the
 * style brief §3. Each symbol is `ph-<name>` or `ph-<name>-fill`; use it with
 *   <svg class="ph"><use href="icons/phosphor.svg#ph-cube"/></svg>
 * Add a name to ICONS and re-run `node tools/make-icons.mjs`; the sprite is committed so the
 * page needs no build step and no icon font.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'node_modules', '@phosphor-icons', 'core', 'assets');

/* name -> the weights to include (regular always; fill where an "active" state exists) */
const ICONS = {
  // workspace tabs
  'cube': ['regular', 'fill'], 'palette': ['regular', 'fill'], 'tag': ['regular', 'fill'],
  'list-checks': ['regular', 'fill'], 'wrench': ['regular', 'fill'],
  // top bar
  'folder-simple': ['regular'], 'caret-down': ['regular'], 'caret-right': ['regular'], 'sun': ['regular'], 'moon': ['regular', 'fill'],
  'share-network': ['regular'], 'chat-circle-dots': ['regular'], 'printer': ['regular'], 'ruler': ['regular'],
  'desk': ['regular'], 'wall': ['regular'], 'table': ['regular'],
  // library + inspector
  'plus': ['regular'], 'minus': ['regular'], 'x': ['regular'], 'copy': ['regular'], 'trash': ['regular'],
  'arrows-out-simple': ['regular'], 'eye': ['regular'], 'sparkle': ['regular', 'fill'], 'play': ['regular', 'fill'],
  'warning': ['regular', 'fill'], 'check': ['regular'], 'info': ['regular'], 'lock-simple': ['regular'], 'pause': ['regular', 'fill'], 'skip-forward': ['regular'], 'image': ['regular'],
  // toolbar + dock
  'cube-focus': ['regular'], 'arrows-out': ['regular'], 'crosshair-simple': ['regular'], 'grid-four': ['regular', 'fill'],
  'gauge': ['regular'], 'arrow-right': ['regular'], 'arrow-counter-clockwise': ['regular'], 'arrow-clockwise': ['regular'],
  'magnifying-glass': ['regular'], 'sliders-horizontal': ['regular'], 'stack': ['regular'],
};

const body = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();

async function main() {
  const symbols = [];
  for (const [name, weights] of Object.entries(ICONS)) {
    for (const w of weights) {
      const file = join(SRC, w, w === 'regular' ? `${name}.svg` : `${name}-${w}.svg`);
      const svg = await readFile(file, 'utf8');
      const id = w === 'regular' ? `ph-${name}` : `ph-${name}-${w}`;
      symbols.push(`<symbol id="${id}" viewBox="0 0 256 256">${body(svg)}</symbol>`);
    }
  }
  const out = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><!-- generated by tools/make-icons.mjs from @phosphor-icons/core; do not edit -->\n${symbols.join('\n')}\n</svg>\n`;
  await mkdir(join(root, 'icons'), { recursive: true });
  await writeFile(join(root, 'icons', 'phosphor.svg'), out);
  console.log(`${symbols.length} symbols -> icons/phosphor.svg (${(out.length / 1024).toFixed(1)} KB)`);
}
main().catch((e) => { console.error(e); process.exit(1); });
